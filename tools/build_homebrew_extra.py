SLUG_RE = re.compile(r"^[a-z0-9-]+$")


def normalize_title(title):
    """Titulo normalizado para deteccao de duplicata.

    Minusculas, sem acentos e sem pontuacao/espacos. Assim "XeXMenu" e
    "XeX Menu" colidem (mesma entrada), enquanto "xeBuild" e "xeBuild GUI"
    continuam distintos, como pedido.
    """
    t = unicodedata.normalize("NFKD", title)
    t = "".join(c for c in t if not unicodedata.combining(c))
    t = t.lower()
    t = re.sub(r"[^a-z0-9]+", "", t)
    return t


def loose_title(title):
    """Normalizacao frouxa (ignora parenteses e sufixos de console) so para AVISO."""
    t = normalize_title(re.sub(r"\(.*?\)", " ", title))
    for suf in ("xbox360", "xbox", "x360", "360"):
        if t.endswith(suf) and len(t) > len(suf) + 2:
            t = t[: -len(suf)]
    return t


def build_new():
    out = []
    for slug, console, title, wiki, year, category, devs, desc, url, verified in ENTRIES:
        assert SLUG_RE.match(slug), "slug invalido: %r" % slug
        assert console in CONSOLES, "console invalido: %r (%s)" % (console, title)
        assert category in CATEGORIES, "categoria invalida: %r (%s)" % (category, title)
        assert verified in VERIFIED, "verified invalido: %r (%s)" % (verified, title)
        assert isinstance(devs, list) and devs, "developers vazio: %s" % title
        assert desc and desc.strip().endswith("."), "descricao sem ponto final: %s" % title
        assert year is None or (1999 <= year <= 2026), "ano suspeito: %r (%s)" % (year, title)
        out.append({
            "id": "hb-" + slug,
            "platform": "homebrew",
            "console": console,
            "title": title,
            "wiki": wiki,
            "year": year,
            "category": category,
            "developers": list(devs),
            "description": desc,
            "url": url,
            "image": None,
            "verified": verified,
        })
    return out


